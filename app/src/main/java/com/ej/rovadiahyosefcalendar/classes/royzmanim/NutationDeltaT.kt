    private fun espenakMeeus(y: Double): Double {
        if (y >= 1986 && y < 2005) {
            val t = y - 2000
            return 63.86 + t * (0.3345 + t * (-0.060374 + t * (0.0017275 + t * (0.000651814 + t * 0.00002373599))))
        }
        if (y >= 1961 && y < 1986) {
            val t = y - 1975
            return 45.45 + 1.067 * t - t * t / 260 - t * t * t / 718
        }
        return -20 + 32 * ((y - 1820) / 100).pow(2)
    }

    /** Delta-T in seconds. @param jd Julian day (UT) */
    @JvmStatic
    fun deltaT(jd: Double): Double {
        val y = 2000 + (jd - 2451544.5) / 365.25
        if (y < TABLE_START) return espenakMeeus(y)
        if (y >= TABLE_END) {
            val dy = y - TABLE_END
            return TABLE[TABLE.size - 1] + TABLE_RATE * dy + 0.0032 * dy * dy
        }
        val x = (y - TABLE_START) / TABLE_STEP
        val i = floor(x).toInt()
        return TABLE[i] + (TABLE[i + 1] - TABLE[i]) * (x - i)
    }

    /**
     * UT1 - UTC in seconds: 32.184 s + (TAI - UTC) - Delta-T, kept within 0.9 s; 0 before 1972.
     * @param jd Julian day (UTC)
     */
    @JvmStatic
    fun ut1MinusUtc(jd: Double): Double {
        if (jd < LEAP_SECONDS[0]) return 0.0
        var i = LEAP_SECONDS.size / 2 - 1
        while (jd < LEAP_SECONDS[2 * i]) i--
        val d = 32.184 + LEAP_SECONDS[2 * i + 1] - deltaT(jd)
        return max(-0.9, min(0.9, d))
    }
