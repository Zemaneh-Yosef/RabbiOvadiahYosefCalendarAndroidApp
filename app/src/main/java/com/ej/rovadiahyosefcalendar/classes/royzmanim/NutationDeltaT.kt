    /**
     * Nutation in longitude and obliquity.
     * @param jce Julian centuries of TT from J2000.0
     * @return [dpsi, deps] in arcseconds
     */
    @JvmStatic
    fun nutation(jce: Double): DoubleArray {
        val t = jce
        val l = ((485868.249036 + 1717915923.2178 * t) % TURNAS) * AS2R
        val lp = ((1287104.79305 + 129596581.0481 * t) % TURNAS) * AS2R
        val f = ((335779.526232 + 1739527262.8478 * t) % TURNAS) * AS2R
        val d = ((1072260.70369 + 1602961601.2090 * t) % TURNAS) * AS2R
        val om = ((450160.398036 - 6962890.5431 * t) % TURNAS) * AS2R
        var dp = 0.0
        var de = 0.0
        var i = TERMS.size - 11
        while (i >= 0) { // smallest terms first
            val arg = TERMS[i] * l + TERMS[i + 1] * lp + TERMS[i + 2] * f + TERMS[i + 3] * d + TERMS[i + 4] * om
            val s = sin(arg)
            val k = cos(arg)
            dp += (TERMS[i + 5] + TERMS[i + 6] * t) * s + TERMS[i + 7] * k
            de += (TERMS[i + 8] + TERMS[i + 9] * t) * k + TERMS[i + 10] * s
            i -= 11
        }
        return doubleArrayOf(dp * 1e-7 - 0.000135, de * 1e-7 + 0.000388)
    }
}

